from __future__ import annotations
import pickle,json
from pathlib import Path
import numpy as np
import pandas as pd

MODEL_PATH=Path(__file__).resolve().parents[3]/"experiments/models/carbon_model.pkl"
PORTABLE_PATH=Path(__file__).resolve().parents[3]/"experiments/models_portable/carbon_model.json"

def model_artifact_path():
    """The distributed JSON model is executable without unsafe deserialization."""
    return PORTABLE_PATH if PORTABLE_PATH.exists() else MODEL_PATH

def seasonal(past,issue):
    series=past.grid_ci_actual_g_per_kwh.dropna()
    if series.empty: raise ValueError("No valid past carbon observations")
    values=[]
    for slot in range(48):
        target=issue+pd.Timedelta(minutes=30*slot)
        samples=[series.get(target-pd.Timedelta(days=k),np.nan) for k in range(1,8)]
        valid=[x for x in samples if np.isfinite(x)]
        values.append(float(np.median(valid)) if valid else float(series.iloc[-1]))
    return np.array(values)

def features(past,issue):
    """Every lookup is earlier than issue; target calendar fields are predetermined."""
    series=past.grid_ci_actual_g_per_kwh
    if not (series.index<issue).all(): raise ValueError("Past feature frame contains decision/future records")
    known=series.dropna()
    if known.empty: raise ValueError("No valid prior CI")
    latest=float(known.iloc[-1]); rows=[]
    for slot in range(48):
        target=issue+pd.Timedelta(minutes=30*slot)
        row=[slot,issue.dayofweek,issue.dayofyear,np.sin(2*np.pi*slot/48),np.cos(2*np.pi*slot/48),latest,float(known.tail(48).mean()),float(known.tail(336).mean())]
        for day in range(1,8):
            v=series.get(target-pd.Timedelta(days=day),np.nan)
            row.append(float(v) if np.isfinite(v) else latest)
        rows.append(row)
    return np.array(rows)

def predict_day(past,issue):
    if PORTABLE_PATH.exists():
        from backend.app.services.lineage import portable_predict
        artifact=json.loads(PORTABLE_PATH.read_text(encoding="utf-8"))
        metadata=artifact["metadata"]
        if issue>=pd.Timestamp(metadata["usable_from"]) and issue>pd.Timestamp(metadata["training_end"]):
            if metadata["selected_method"]=="seven_day_seasonal_median":
                return seasonal(past,issue),metadata["version"]
            values=portable_predict(artifact,features(past,issue).tolist())
            return np.clip(values,0,1500),metadata["version"]
    if MODEL_PATH.exists():
        with MODEL_PATH.open("rb") as handle: artifact=pickle.load(handle)
        # Trusted local artifact generated by train_models.py. Never accept uploaded pickle.
        # Selection is learned information too: never use future validation choice.
        usable_from=pd.Timestamp(artifact.get("usable_from","2025-09-01T00:00:00Z"))
        if issue>=usable_from and issue>pd.Timestamp(artifact["training_end"]):
            if artifact.get("selected_method")=="seven_day_seasonal_median":
                return seasonal(past,issue),artifact["version"]
            return np.clip(artifact["model"].booster_.predict(features(past,issue),num_threads=1),0,1500),artifact["version"]
    return seasonal(past,issue),"past-only-seven-day-seasonal-median-v1"
